using System;
using System.Collections.Generic;
using System.Linq;
using DistributionSystem.Business.Dtos;
using DistributionSystem.Data.Data;
using DistributionSystem.Data.Entities;
using DistributionSystem.Data.Repositories;

namespace DistributionSystem.Business.Services
{
    public class EmployeeService : BaseService
    {
        private readonly EmployeeRepository _repo;

        public EmployeeService()
        {
            _repo = new EmployeeRepository(new SqlConnectionFactory());
        }

        // ??????????????????????????????????????????????????????
        //  EMPLOYEES
        // ??????????????????????????????????????????????????????
        public List<EmployeeDto> GetAllEmployees()
            => Execute(() => _repo.GetAllEmployees().Select(ToDto).ToList());

        public void AddEmployee(EmployeeDto dto)
        {
            Execute<object>(() =>
            {
                if (string.IsNullOrWhiteSpace(dto.Name)) throw new ValidationException("«”„ «·„ÊŸ› „ÿ·Ê».");
                if (dto.Salary <= 0) throw new ValidationException("«·„— » ÌÃ» √‰ ÌﬂÊ‰ √ﬂ»— „‰ ’›—.");
                _repo.InsertEmployee(new Employee
                {
                    Name = dto.Name.Trim(),
                    Salary = dto.Salary,
                    Notes = dto.Notes ?? "",
                    JobTitle = dto.JobTitle?.Trim() ?? "" // ?
                });
                return null;
            });
        }

        public void UpdateEmployee(EmployeeDto dto)
        {
            Execute<object>(() =>
            {
                if (string.IsNullOrWhiteSpace(dto.Name)) throw new ValidationException("«”„ «·„ÊŸ› „ÿ·Ê».");
                if (dto.Salary <= 0) throw new ValidationException("«·„— » ÌÃ» √‰ ÌﬂÊ‰ √ﬂ»— „‰ ’›—.");
                _repo.UpdateEmployee(new Employee
                {
                    Id = dto.Id,
                    Name = dto.Name.Trim(),
                    Salary = dto.Salary,
                    Notes = dto.Notes ?? "",
                    JobTitle = dto.JobTitle?.Trim() ?? "" // ?
                });
                return null;
            });
        }

        public void DeleteEmployee(int id)
            => Execute<object>(() => { _repo.DeleteEmployee(id); return null; });

        // ??????????????????????????????????????????????????????
        //  LOANS
        // ??????????????????????????????????????????????????????
        public void AddLoan(EmployeeLoanDto dto)
        {
            Execute<object>(() =>
            {
                if (dto.Amount <= 0) throw new ValidationException("„»·€ «·”·›… ÌÃ» √‰ ÌﬂÊ‰ √ﬂ»— „‰ ’›—.");
                _repo.AddLoan(new EmployeeLoan
                {
                    EmployeeId = dto.EmployeeId,
                    Amount = dto.Amount,
                    Notes = dto.Notes ?? ""
                });
                return null;
            });
        }

        // ??????????????????????????????????????????????????????
        //  ADMIN EXPENSES
        // ??????????????????????????????????????????????????????
        public List<AdminExpenseDto> GetAllExpenses()
            => Execute(() => _repo.GetAllExpenses().Select(e => new AdminExpenseDto
            {
                Id = e.Id,
                Description = e.Description,
                Amount = e.Amount,
                CreatedAt = e.CreatedAt
            }).ToList());

        public void AddExpense(AdminExpenseDto dto)
        {
            Execute<object>(() =>
            {
                if (string.IsNullOrWhiteSpace(dto.Description)) throw new ValidationException("»‰œ «·„’—Ê› „ÿ·Ê».");
                if (dto.Amount <= 0) throw new ValidationException("«·„»·€ ÌÃ» √‰ ÌﬂÊ‰ √ﬂ»— „‰ ’›—.");
                _repo.InsertExpense(new AdminExpense { Description = dto.Description.Trim(), Amount = dto.Amount });
                return null;
            });
        }

        public void DeleteExpense(int id)
            => Execute<object>(() => { _repo.DeleteExpense(id); return null; });

        // ??????????????????????????????????????????????????????
        //  SUMMARIES
        // ??????????????????????????????????????????????????????
        public decimal GetTotalPaidToEmployees() => Execute(() => _repo.GetTotalPaidToEmployees());
        public decimal GetTotalAdminExpenses() => Execute(() => _repo.GetTotalAdminExpenses());

        // ??????????????????????????????????????????????????????
        //  HELPER
        // ??????????????????????????????????????????????????????
        private static EmployeeDto ToDto(Employee e) => new EmployeeDto
        {
            Id = e.Id,
            Name = e.Name,
            Salary = e.Salary,
            RemainingBalance = e.RemainingBalance,
            TotalLoans = e.Salary - e.RemainingBalance,
            Notes = e.Notes,
            JobTitle = e.JobTitle, // ?
            IsActive = e.IsActive,
            CreatedAt = e.CreatedAt
        };
    }
}